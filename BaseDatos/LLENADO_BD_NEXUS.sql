SELECT SUM(ProgramaEducativoEE.Creditos) AS creditos_acumulados
FROM ProgramaEducativoEE
WHERE ProgramaEducativoEE.IdProgramaEducativo = 1
  AND ProgramaEducativoEE.IdEE IN (
    SELECT Grupo.IdEE
    FROM Inscripcion
    JOIN Grupo ON Grupo.IdGrupo = Inscripcion.IdGrupo
    WHERE Inscripcion.IdAlumno = 1 AND Inscripcion.Estado = 'APROBADA'
  );

SELECT SUM(ProgramaEducativoEE.Creditos) AS creditos_del_semestre
FROM ProgramaEducativoEE
WHERE ProgramaEducativoEE.IdProgramaEducativo = 1
  AND ProgramaEducativoEE.IdEE IN (
    SELECT Grupo.IdEE
    FROM Inscripcion
    JOIN Grupo ON Grupo.IdGrupo = Inscripcion.IdGrupo
    WHERE Inscripcion.IdAlumno = 1 AND Inscripcion.Estado = 'CURSANDO' AND Grupo.IdPeriodo = 9
  );

SELECT Usuario.NombreUsuario, STRING_AGG(Rol.NombreRol, ', ' ORDER BY Rol.NombreRol) AS roles
FROM Usuario
JOIN UsuarioRol ON UsuarioRol.IdUsuario = Usuario.IdUsuario
JOIN Rol ON Rol.IdRol = UsuarioRol.IdRol
GROUP BY Usuario.IdUsuario, Usuario.NombreUsuario
ORDER BY Usuario.IdUsuario;