UNION ALL SELECT 'prerrequisitos', COUNT(*), 19 FROM Prerrequisito
UNION ALL SELECT 'periodos', COUNT(*), 9 FROM Periodo
UNION ALL SELECT 'usuarios', COUNT(*), 60 FROM Usuario
